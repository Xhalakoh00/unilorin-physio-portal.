// @route   POST /api/admin/candidates
// @desc    Add a new candidate with an image upload
router.post('/candidates', upload.single('image'), async (req, res) => {
  const { fullName, positionId, level, manifesto } = req.body;

  if (!fullName || !positionId || !level) {
    return res.status(400).json({ success: false, message: 'All fields are required.' });
  }

  try {
    // req.file.path contains the secure Cloudinary URL automatically generated by our middleware
    const imageUrl = req.file ? req.file.path : '';

    const newCandidate = await Candidate.create({
      fullName,
      position: positionId,
      level,
      manifesto,
      imageUrl,
    });

    res.status(201).json({
      success: true,
      message: 'Candidate and photo successfully uploaded.',
      candidate: newCandidate,
    });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
});
